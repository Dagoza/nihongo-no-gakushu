const vocabN4 = require('../data/vocabulary_n4.json');
const vocabN5 = require('../data/vocabulary_n5.json');

const dictMap = new Map();

function addWord(k, r) {
  if (!k || !r) return;
  k = k.trim();
  r = r.trim();
  if (!/[\u4e00-\u9faf\u3400-\u4dbf\u3005]/.test(k)) return;
  if (/[\s,.!?。、！？・〜~「」()（）]/.test(k)) return;
  
  // Do not add full phrases with kana prefix and suffix (e.g., "お先に失礼します")
  if (/^[\u3040-\u309f\u30a0-\u30ff].*[\u4e00-\u9faf\u3400-\u4dbf].*[\u3040-\u309f\u30a0-\u30ff]$/.test(k)) {
    // Only allow if it's a known single-word lexical unit like "お茶", "ご飯", "お願い", etc.
    const allowedLexical = [
      'お茶', 'ご飯', 'お願い', 'お弁当', 'お箸', 'お土産', 'お風呂', 'お母さん', 'お父さん',
      'お兄さん', 'お姉さん', 'お酒', 'お腹', 'お皿', 'お湯', 'お寺', 'お祝い', 'お礼', 'お詫び'
    ];
    if (!allowedLexical.includes(k)) return;
  }
  
  dictMap.set(k, r);
}

// 1. Dictionary
dictionary.forEach(d => addWord(d.kanji, d.hiragana));

// 2. Vocab files
[...vocab, ...(vocabN4.vocabulary || []), ...vocabN5].forEach(v => {
  addWord(v.kanji, v.kana || v.hiragana);
});

// 3. Kanji words & readings
kanji.forEach(k => {
  (k.words || []).forEach(w => addWord(w.word, w.reading));
});

// 4. Curriculum vocab
curriculum.forEach(s => {
  (s.vocab_details || []).forEach(v => addWord(v.kanji, v.kana));
  (s.sections || []).forEach(sec => {
    (sec.vocabulary || sec.vocab || []).forEach(v => addWord(v.kanji, v.kana));
  });
});

